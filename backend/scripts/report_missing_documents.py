"""List uncovered registry topics for which the user must obtain source material."""

from __future__ import annotations

import json
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
RAW_DOCS = BACKEND / "data" / "raw_docs"
REGISTRY = BACKEND / "data" / "uncovered_conditions.json"
OUTPUT = BACKEND / "data" / "DOCUMENTS_TO_OBTAIN.md"


def main() -> None:
    conditions = json.loads(REGISTRY.read_text(encoding="utf-8"))["conditions"]
    # These are official landing pages to search for source documents, not claims
    # that a specific PDF exists or is already part of this project.
    portals = ("https://mohfw.gov.in/", "https://nhm.gov.in/", "https://www.icmr.gov.in/",
               "https://nhp.gov.in/", "https://www.who.int/health-topics/")
    official_leads = {
        "rabies": ("[NCDC National Guidelines for Rabies Prophylaxis (39 MB)]"
                   "(https://ncdc.mohfw.gov.in/uploads/resource/1769332447_National-Guidelines-for-Rabies-Prophylaxis.pdf)"),
        "animal-bite rabies exposure": ("[NCDC National Guidelines for Rabies Prophylaxis (39 MB)]"
                   "(https://ncdc.mohfw.gov.in/uploads/resource/1769332447_National-Guidelines-for-Rabies-Prophylaxis.pdf)"),
        "rabies post-exposure care": ("[NCDC National Guidelines for Rabies Prophylaxis (39 MB)]"
                   "(https://ncdc.mohfw.gov.in/uploads/resource/1769332447_National-Guidelines-for-Rabies-Prophylaxis.pdf)"),
        "snakebite": ("[NCDC National Action Plan for Snakebite Envenoming (5.9 MB)]"
                   "(https://ncdc.mohfw.gov.in/uploads/resource/1769335066_NATIONAL-ACTION-PLAN-FOR-PREVENTION-AND-CONTROL-OF-SNAKEBITE-ENVENOMING-NAPSE.pdf)"),
        "heatstroke": ("[NCDC Emergency Cooling for Severe Heat-Related Illnesses (2024)]"
                   "(https://ncdc.mohfw.gov.in/uploads/resource/1769333089_Emergency-Cooling-for-Severe-Heat-Related-Illnesses_March2024_NPCCHH.pdf) · "
                   "[NCDC Heatwave Public Health Advisory (2024)]"
                   "(https://ncdc.mohfw.gov.in/uploads/resource/1769333176_NPCCHH_Public-health-advisory_Extreme-heat_Heatwave_2024.pdf)"),
        "neonatal sepsis": ("[NHM F-IMNCI Participant Module (2023)]"
                   "(https://www.nhm.gov.in/images/pdf/programmes/child-health/guidelines/Revised-F-IMNCI-Modules-2023/FIMNCI-Participant-Module-2023.pdf)"),
    }
    existing = " ".join(path.stem.casefold().replace("_", " ") for path in RAW_DOCS.iterdir() if path.is_file())
    missing = [item for item in conditions if not any(alias.casefold() in existing for alias in item["aliases"])]
    lines = ["# Official source documents to obtain", "",
             "This report identifies uncovered registry topics with no obvious matching local filename. "
             "Obtain current official guidance PDFs or text, then add them to `data/raw_docs` and register their hashes in `SOURCES.md`. "
             "A linked lead is not downloaded, reviewed for ingestion, or included in the index. Confirm scope, currentness, and applicable passages before use. "
             "No document text is generated by this script.", "",
             f"Generated from {len(conditions)} uncovered topics; {len(missing)} appear missing by filename.", "",
             "| Topic | Verified official lead (if found) | Other official portals to search |", "|---|---|---|"]
    for item in missing:
        lead = official_leads.get(item["label"].casefold(), "Not yet identified")
        lines.append(f"| {item['label']} | {lead} | " + " · ".join(f"[{portal.split('/')[2]}]({portal})" for portal in portals) + " |")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(missing)} candidate missing-source topics to {OUTPUT}")


if __name__ == "__main__":
    main()
