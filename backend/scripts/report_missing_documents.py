"""List uncovered registry topics for which the user must obtain source material."""

from __future__ import annotations

import json
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
RAW_DOCS = BACKEND / "data" / "raw_docs"
REGISTRY = BACKEND / "data" / "uncovered_conditions.json"
OUTPUT = BACKEND / "data" / "DOCUMENTS_TO_OBTAIN.md"


def main() -> None:
    conditions = json.loads(REGISTRY.read_text(encoding="utf-8"))["conditions"]
    # These are official landing pages to search for source documents, not claims
    # that a specific PDF exists or is already part of this project.
    portals = ("https://mohfw.gov.in/", "https://nhm.gov.in/", "https://www.icmr.gov.in/",
               "https://nhp.gov.in/", "https://www.who.int/health-topics/")
    existing = " ".join(path.stem.casefold().replace("_", " ") for path in RAW_DOCS.iterdir() if path.is_file())
    missing = [item for item in conditions if not any(alias.casefold() in existing for alias in item["aliases"])]
    lines = ["# Official source documents to obtain", "",
             "This report identifies uncovered registry topics with no obvious matching local filename. "
             "Obtain current official guidance PDFs or text, then add them to `data/raw_docs` and register their hashes in `SOURCES.md`. "
             "No document text is generated by this script.", "",
             f"Generated from {len(conditions)} uncovered topics; {len(missing)} appear missing by filename.", "",
             "| Topic | Suggested official portals to search |", "|---|---|"]
    for item in missing:
        lines.append(f"| {item['label']} | " + " · ".join(f"[{portal.split('/')[2]}]({portal})" for portal in portals) + " |")
    OUTPUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {len(missing)} candidate missing-source topics to {OUTPUT}")


if __name__ == "__main__":
    main()
